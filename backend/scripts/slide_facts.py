#!/usr/bin/env python3
"""Recompute docs/SLIDE_FACTS.md from the seeded data and the matcher evaluation. Run after `make seed`."""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.db import session_scope  # noqa: E402
from app.models import OverlapAlert  # noqa: E402
from app.routers.dashboard import stats  # noqa: E402
from sqlalchemy import select  # noqa: E402

DOCS = Path(__file__).resolve().parents[2] / "docs"


def main() -> None:
    with session_scope() as db:
        s = stats(db)
        alerts = db.execute(select(OverlapAlert).where(OverlapAlert.status == "open")).scalars().all()
        al = "; ".join(f"{a.institution.name} {a.score:.0f}/100 ({len(a.pairs)} pair)" for a in alerts)
    t = s["totals"]
    ev = (DOCS / "MATCHING_EVAL.md").read_text() if (DOCS / "MATCHING_EVAL.md").exists() else ""
    name = re.search(r"\| hybrid @ 80 \| ([\d.]+) \| ([\d.]+) \|", ev)
    pair = re.search(r"\| full scorer @ 65 \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \|", ev)
    multi = sum(1 for r in s["institutions"] if len(r["units"]) > 1)
    (DOCS / "SLIDE_FACTS.md").write_text(f"""# Slide facts (generated by `make facts` from the seeded synthetic data, as of {s['today']})

All numbers describe synthetic demo data, not AICTE records.

| Fact | Value |
|---|---|
| Fictional institutions / units / cases | 12 / 4 / {t['received']} |
| Open (pending) / disposed | {t['pending']} / {t['disposed']} |
| Overdue open cases | {t['overdue']} |
| Escalated / transferred (pending acceptance) | {t['escalated']} / {t['transferred']} |
| Average age of open cases | {s['avg_open_age']} days |
| Disposal rate / disposed within SLA | {s['disposal_rate']}% / {s['disposed_in_time_pct']}% |
| Institutions with open cases in more than one unit | {multi} |
| Open overlap alerts after seeding | {len(alerts)}: {al} |
| Typed name -> institution (synthetic test set, threshold 80) | precision {name.group(1) if name else '?'}, recall {name.group(2) if name else '?'} |
| Case-pair overlap (synthetic test set, threshold 65) | precision {pair.group(1) if pair else '?'}, recall {pair.group(2) if pair else '?'}, false-positive rate {pair.group(3) if pair else '?'} |

Say "on our synthetic test set" whenever you quote the precision and recall figures.
""")
    print((DOCS / "SLIDE_FACTS.md").read_text())


if __name__ == "__main__":
    main()
